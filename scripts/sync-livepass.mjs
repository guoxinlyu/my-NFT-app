import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const deployment = JSON.parse(fs.readFileSync(path.join(root, 'contracts/deployments/sepolia.json'), 'utf8'));
const artifact = JSON.parse(fs.readFileSync(path.join(root, 'contracts/deployments/sepolia-build/LivePass.json'), 'utf8'));
if (deployment.chainId !== 11155111 || !deployment.blockNumber || !deployment.runtimeBytecodeHash) throw new Error('Verified Sepolia deployment required');
fs.mkdirSync(path.join(root, 'src/livepass'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/livepass/contract.ts'),
  '// Generated by scripts/sync-livepass.mjs from the verified deployment.\n' +
  `export const DEPLOYMENT = ${JSON.stringify({ chainId: deployment.chainId, address: deployment.address, blockNumber: deployment.blockNumber, runtimeBytecodeHash: deployment.runtimeBytecodeHash }, null, 2)} as const;\n` +
  `export const LIVEPASS_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`);
